"""Write tests/data/enroute_vectors.json: en-route cases with their answers.

The dashboard (analysis/enroute.py) and the phone (route/EnRoute.kt) must
judge a trip in progress the same way. Both test suites run every case in
this file and compare with the answers recorded here, which come from the
Python. tests/test_enroute.py fails when the file is stale; regenerate with

    python tools/export_enroute_vectors.py

Two plans: a hand-made one that is easy to check (300 km, a stop at km 100
with alternatives either side) and a real one from the planner (400 km north,
chargers every 25 km).
"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from analysis.enroute import assess  # noqa: E402
from routing.planner import CarModel, Charger, PlanSettings, plan_trip  # noqa: E402

OUT = os.path.join(ROOT, "tests", "data", "enroute_vectors.json")

HAND = {
    "start_pct": 90.0, "distance_km": 300.0, "arrival_pct": 15.0,
    "profile": [[0, 90.0], [100, 20.0], [100, 80.0], [300, 15.0]],
    "stops": [{"km": 100.0, "name": "Hub", "id": "1", "arrive_pct": 20.0,
               "alternatives": [{"km": 90.0, "name": "Before", "id": "2"},
                                {"km": 110.0, "name": "After", "id": "3"}]}],
}


def _real() -> dict:
    road = [(50.0 + k / 111.195, 0.0, None) for k in range(401)]
    chargers = [Charger(f"C{k}", road[k][0], 0.0, 150, id=str(k))
                for k in range(50, 400, 25)]
    p = plan_trip(road, 15000, 90, CarModel(53.2, 0.17), PlanSettings(),
                  chargers).as_dict()
    return {"start_pct": p["start_pct"], "distance_km": round(p["distance_km"], 3),
            "arrival_pct": p["arrival_pct"], "profile": p["profile"],
            "stops": [{"km": s["km"], "name": s["name"], "id": s["id"],
                       "arrive_pct": s["arrive_pct"],
                       "alternatives": [{"km": a["km"], "name": a["name"], "id": a["id"]}
                                        for a in s["alternatives"]]}
                      for s in p["stops"]]}


def _cases():
    # (name, plan, km_along, actual_pct, reading_age_s, reserve_pct, charged)
    yield "on plan", "hand", 50, 55.0, 0, 10, False
    yield "more than planned: the gap grows", "hand", 37.5, 58.5, 0, 10, False
    yield "warning: stop still fine", "hand", 90, 23.5, 0, 10, False
    yield "adjust: tight", "hand", 50, 51.0, 0, 10, False
    yield "critical: alternatives in reach", "hand", 60, 40.0, 0, 10, False
    yield "stale reading", "hand", 60, 20.0, 3600, 10, False
    yield "at the stop", "hand", 99, 19.0, 0, 10, False
    yield "charged since the plan", "hand", 50, 51.0, 0, 10, True
    yield "above plan", "hand", 50, 61.0, 0, 10, False
    yield "after the stop", "hand", 200, 40.0, 0, 10, False
    yield "higher reserve", "hand", 50, 52.0, 0, 15, False
    yield "real: on plan", "real", 120, None, 0, 10, False
    yield "real: well below", "real", 120, -25.0, 0, 10, False
    yield "real: below, near the stop", "real", -40, -6.0, 0, 10, False


def build() -> dict:
    from analysis.enroute import expected_pct
    plans = {"hand": HAND, "real": _real()}
    first = plans["real"]["stops"][0]["km"]
    cases = []
    for name, which, km, actual, age, reserve, charged in _cases():
        plan = plans[which]
        if which == "real":
            km = first + km if km < 0 else km
            on = expected_pct(plan["profile"], km)
            actual = on if actual is None else on + actual
        got = assess(plan, km, actual, reading_age_s=age, reserve_pct=reserve,
                     charged_since_plan=charged)
        cases.append({
            "name": name, "plan": which, "km_along": km, "actual_pct": round(actual, 3),
            "reading_age_s": age, "reserve_pct": reserve, "charged_since_plan": charged,
            "expect": {k: got.get(k) for k in (
                "level", "replan", "expected_pct", "deviation_pct", "ratio",
                "target_km", "planned_target_pct", "projected_target_pct",
                "shortfall_pct", "reach_km", "at_stop", "stale_reading")}
            | {"alternatives": [a["name"] for a in got["alternatives"]]},
        })
    return {"_comment": "Generated by tools/export_enroute_vectors.py -- do not edit.",
            "plans": plans, "cases": cases}


def render(data: dict) -> str:
    return json.dumps(data, indent=1, sort_keys=True) + "\n"


def main() -> None:
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render(build()))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
