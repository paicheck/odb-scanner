"""Write tests/data/handoff_vectors.json: Google Maps links with their answers.

The dashboard (routing/handoff.py) and the phone (route/GoogleMaps.kt) must
build the same link for the same trip; both test suites check every case
here, which comes from the Python. tests/test_handoff.py fails when the file
is stale; regenerate with

    python tools/export_handoff_vectors.py
"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from routing.handoff import MAX_WAYPOINTS_BROWSER, next_stop_intent, trip_link  # noqa: E402

OUT = os.path.join(ROOT, "tests", "data", "handoff_vectors.json")
OXFORD, LEEDS = (51.752, -1.2577), (53.8008, -1.5491)
STOPS = [(52.0 + i * 0.15, -1.3 - i * 0.02) for i in range(11)]


def _cases():
    yield {"name": "direct, from here", "origin": OXFORD, "stops": [],
           "destination": LEEDS}
    yield {"name": "two stops, keeping off motorways and tolls", "origin": OXFORD,
           "stops": STOPS[:2], "destination": LEEDS,
           "avoid": {"motorways": True, "tolls": True, "ferries": False}}
    yield {"name": "eleven stops: as far as the tenth", "origin": OXFORD, "stops": STOPS,
           "destination": LEEDS}
    yield {"name": "a mobile browser takes three", "origin": OXFORD, "stops": STOPS[:5],
           "destination": LEEDS, "max_waypoints": MAX_WAYPOINTS_BROWSER}
    yield {"name": "no origin: Google Maps uses the phone's position", "origin": None,
           "stops": STOPS[:1], "destination": LEEDS}
    yield {"name": "southern and western coordinates", "origin": (-33.8688, 151.2093),
           "stops": [(-34.4278, 150.8931)], "destination": (-35.2809, 149.13),
           "avoid": {"ferries": True}}
    yield {"name": "preview only", "origin": OXFORD, "stops": STOPS[:1],
           "destination": LEEDS, "navigate": False}


def build() -> dict:
    cases = []
    for c in _cases():
        h = trip_link(c["origin"], c["stops"], c["destination"], c.get("avoid"),
                      c.get("max_waypoints", 9), c.get("navigate", True))
        cases.append(dict(c, expect={"url": h.url, "stops_sent": h.stops_sent,
                                     "partial": h.partial}))
    intents = [{"target": LEEDS, "avoid": a, "expect": next_stop_intent(LEEDS, a)}
               for a in (None, {"tolls": True, "motorways": True, "ferries": True},
                         {"ferries": True})]
    return {"_comment": "Generated by tools/export_handoff_vectors.py -- do not edit.",
            "trip_links": cases, "next_stop_intents": intents}


def render(data: dict) -> str:
    return json.dumps(data, indent=1, sort_keys=True) + "\n"


def main() -> None:
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render(build()))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
